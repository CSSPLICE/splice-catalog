import type { ProvisionalUsageEvent } from '../db/entities/ProvisionalUsageEvent.js';
import type { CatalogSnapshot } from './SessionBehaviorObserver.js';

export type CampaignEvidence = Pick<ProvisionalUsageEvent, 'id' | 'sessionKey' | 'kind' | 'identityKey' | 'receivedAt'>;
export interface CampaignRequest {
  asOf: Date;
  /** Caller attests that the supplied export is complete over this closed interval. */
  history?: { from: Date; through: Date; complete: boolean };
  catalog?: CatalogSnapshot;
}
export const campaignExperiment = Object.freeze({
  version: 'phase3c-offline-v1',
  bucketMs: 60_000,
  windowsMs: Object.freeze([300_000, 900_000] as const),
  maxInputRows: 100_000,
  maxWindowRows: 20_000,
  maxSessions: 2_000,
  maxSessionRows: 2_000,
  maxMotifs: 10_000,
  maxCatalogEntries: 50_000,
  minSessions: 4,
  minEntryEvents: 20,
  motifLength: 5,
  synchronyMs: 10_000,
  minSynchronizedMotifs: 3,
  coverageFraction: 0.8,
  coverageMinEntries: 20,
  maxSingleSessionCoverage: 0.35,
});
export type CampaignPattern = 'SHARED_ENTRY_SEQUENCES' | 'SYNCHRONIZED_TRAVERSAL' | 'DISTRIBUTED_CATALOG_COVERAGE';
export interface CampaignObservation {
  /** Upsert key: at most one output per pattern/window/minute, never per participant. */
  key: string;
  pattern: CampaignPattern;
  entryEvents: number;
  entrySessions: number;
  explanation: string;
  limitations: readonly string[];
}
export interface CampaignMetrics {
  entryEvents: number;
  entrySessions: number;
  distinctEntries: number;
  sequenceEligibleSessions: number;
  sharedMotifs: number;
  synchronizedMotifs: number;
  maxMotifSessionSupport: number;
  catalogSize: number | null;
  coveredEntries: number | null;
  coverageFraction: number | null;
  outsideCatalogEntries: number | null;
  maxSingleSessionCoverage: number | null;
  catalogContributingSessions: number | null;
}
export interface CampaignWindow {
  windowMs: number;
  startMs: number;
  endMs: number;
  status: 'COMPLETE' | 'INCOMPLETE_HISTORY' | 'INSUFFICIENT_EVIDENCE' | 'CAPACITY' | 'INVALID_INPUT';
  issues: string[];
  availableRows: number;
  coverageStatus: 'KNOWN' | 'UNKNOWN_CATALOG' | 'NOT_ANALYZED';
  sequenceStatus: 'KNOWN' | 'INSUFFICIENT_SEQUENCE_HISTORY' | 'NOT_ANALYZED';
  metrics: CampaignMetrics | null;
  observations: CampaignObservation[];
  work: { motifCandidates: number; distinctMotifs: number; pairwiseComparisons: 0 };
}
export interface CampaignAnalysis {
  version: string;
  bucketEndMs: number;
  windows: CampaignWindow[];
}
type Row = Omit<CampaignEvidence, 'receivedAt'> & { at: number };
const limitations = Object.freeze([
  'Shared sequences and breadth can be generated by professors; no automation attribution or participant exclusion.',
  'Receipt order is not verified page navigation, attention, network provenance or common control.',
  'Motifs may overlap; their counts are correlated evidence, not independent votes.',
  'Window summaries can combine unrelated groups; no single cohort or common controller is established.',
]);
function time(date: Date): number {
  if (!(date instanceof Date) || !Number.isFinite(date.getTime())) throw new Error('INVALID_TIMESTAMP');
  return date.getTime();
}
function validKey(key: string): boolean {
  return typeof key === 'string' && key.length > 0 && key.length <= 64;
}
function blank(windowMs: number, endMs: number): CampaignWindow {
  return {
    windowMs,
    startMs: endMs - windowMs,
    endMs,
    status: 'COMPLETE',
    issues: [],
    availableRows: 0,
    coverageStatus: 'NOT_ANALYZED',
    sequenceStatus: 'NOT_ANALYZED',
    metrics: null,
    observations: [],
    work: { motifCandidates: 0, distinctMotifs: 0, pairwiseComparisons: 0 },
  };
}
function fail(window: CampaignWindow, status: CampaignWindow['status'], issue: string): CampaignWindow {
  return {
    ...window,
    status,
    issues: [...window.issues, issue],
    metrics: null,
    observations: [],
    coverageStatus: 'NOT_ANALYZED',
    sequenceStatus: 'NOT_ANALYZED',
  };
}

/** Stateless offline batch analysis. No runtime imports, IO, labels, networks, UAs or decisions. */
export function observeCampaigns(evidence: readonly CampaignEvidence[], request: CampaignRequest): CampaignAnalysis {
  const p = campaignExperiment;
  const end = Math.floor(time(request.asOf) / p.bucketMs) * p.bucketMs;
  const result: CampaignAnalysis = {
    version: p.version,
    bucketEndMs: end,
    windows: p.windowsMs.map((w) => blank(w, end)),
  };
  const failAll = (status: CampaignWindow['status'], issue: string) => {
    result.windows = result.windows.map((w) => fail(w, status, issue));
    return result;
  };
  if (evidence.length > p.maxInputRows) return failAll('CAPACITY', 'INPUT_ROW_CAPACITY');
  if (request.catalog && request.catalog.entryIdentityKeys.length > p.maxCatalogEntries)
    return failAll('CAPACITY', 'CATALOG_CAPACITY');
  const ids = new Map<number, Row>();
  let history: { from: number; through: number; complete: boolean } | undefined;
  let catalog: Set<string> | null = null;
  try {
    if (request.history)
      history = {
        from: time(request.history.from),
        through: time(request.history.through),
        complete: request.history.complete === true,
      };
    if (history && history.from > history.through) throw new Error('INVALID_HISTORY_INTERVAL');
    if (request.catalog) {
      if (!request.catalog.entryIdentityKeys.every(validKey)) throw new Error('INVALID_CATALOG_KEY');
      if (time(request.catalog.asOf) <= end && request.catalog.entryIdentityKeys.length)
        catalog = new Set(request.catalog.entryIdentityKeys);
    }
    for (const event of evidence) {
      if (
        !Number.isSafeInteger(event.id) ||
        event.id < 0 ||
        !validKey(event.sessionKey) ||
        !validKey(event.identityKey) ||
        !['ENTRY_CLICK', 'EXTERNAL_CLICK', 'WEB_SEARCH'].includes(event.kind)
      )
        throw new Error('INVALID_EVIDENCE');
      const row: Row = {
        id: event.id,
        sessionKey: event.sessionKey,
        identityKey: event.identityKey,
        kind: event.kind,
        at: time(event.receivedAt),
      };
      const previous = ids.get(row.id);
      if (previous && JSON.stringify(previous) !== JSON.stringify(row)) throw new Error('CONFLICTING_LEDGER_ID');
      ids.set(row.id, row);
    }
  } catch {
    return failAll('INVALID_INPUT', 'INVALID_OR_CONFLICTING_EVIDENCE');
  }
  const rows = [...ids.values()].sort((a, b) => a.at - b.at || a.id - b.id);
  result.windows = result.windows.map((window) => {
    // Input is bounded globally; each history and each summary has independent bounds.
    const selected = rows.filter((row) => row.at >= window.startMs && row.at <= end);
    window.availableRows = selected.length;
    if (selected.length > p.maxWindowRows) return fail(window, 'CAPACITY', 'WINDOW_ROW_CAPACITY');
    if (!history || !history.complete || history.from > window.startMs || history.through < end)
      return fail(window, 'INCOMPLETE_HISTORY', 'SOURCE_COMPLETENESS_UNKNOWN');
    return analyzeWindow(window, selected, catalog);
  });
  return result;
}

function analyzeWindow(window: CampaignWindow, rows: Row[], catalog: Set<string> | null): CampaignWindow {
  const p = campaignExperiment;
  const sessions = new Map<string, Row[]>(),
    entries = new Set<string>();
  let entryEvents = 0;
  for (const row of rows) {
    if (row.kind !== 'ENTRY_CLICK') continue;
    const session = sessions.get(row.sessionKey) ?? [];
    if (!sessions.has(row.sessionKey) && sessions.size >= p.maxSessions)
      return fail(window, 'CAPACITY', 'SESSION_CAPACITY');
    if (session.length >= p.maxSessionRows) return fail(window, 'CAPACITY', 'SESSION_ROW_CAPACITY');
    session.push(row);
    sessions.set(row.sessionKey, session);
    entries.add(row.identityKey);
    entryEvents++;
  }
  const metrics: CampaignMetrics = {
    entryEvents,
    entrySessions: sessions.size,
    distinctEntries: entries.size,
    sequenceEligibleSessions: 0,
    sharedMotifs: 0,
    synchronizedMotifs: 0,
    maxMotifSessionSupport: 0,
    catalogSize: catalog?.size ?? null,
    coveredEntries: null,
    coverageFraction: null,
    outsideCatalogEntries: null,
    maxSingleSessionCoverage: null,
    catalogContributingSessions: null,
  };
  window.metrics = metrics;
  window.coverageStatus = catalog ? 'KNOWN' : 'UNKNOWN_CATALOG';
  if (!catalog) window.issues.push('CATALOG_MISSING_EMPTY_OR_FUTURE');
  if (catalog) {
    metrics.coveredEntries = [...entries].filter((key) => catalog.has(key)).length;
    metrics.coverageFraction = metrics.coveredEntries / catalog.size;
    metrics.outsideCatalogEntries = entries.size - metrics.coveredEntries;
    metrics.maxSingleSessionCoverage = 0;
    metrics.catalogContributingSessions = 0;
    for (const session of sessions.values()) {
      const covered = new Set(session.filter((row) => catalog.has(row.identityKey)).map((row) => row.identityKey)).size;
      if (covered) metrics.catalogContributingSessions++;
      metrics.maxSingleSessionCoverage = Math.max(metrics.maxSingleSessionCoverage, covered / catalog.size);
    }
  }
  if (sessions.size < p.minSessions || entryEvents < p.minEntryEvents) {
    window.status = 'INSUFFICIENT_EVIDENCE';
    window.issues.push('NEED_AT_LEAST_4_ENTRY_SESSIONS_AND_20_ENTRY_EVENTS');
    return window;
  }
  const motifs = new Map<string, { support: number; min: number[]; max: number[] }>();
  for (const session of sessions.values()) {
    const seen = new Set<string>(); // One contribution per motif per session, regardless of loops.
    if (session.length >= p.motifLength) metrics.sequenceEligibleSessions++;
    for (let i = 0; i <= session.length - p.motifLength; i++) {
      window.work.motifCandidates++;
      const part = session.slice(i, i + p.motifLength),
        keys = part.map((row) => row.identityKey);
      if (new Set(keys).size !== p.motifLength) continue;
      const key = JSON.stringify(keys);
      if (seen.has(key)) continue;
      seen.add(key);
      let motif = motifs.get(key);
      if (!motif) {
        if (motifs.size >= p.maxMotifs) {
          window.work.distinctMotifs = motifs.size;
          return fail(window, 'CAPACITY', 'MOTIF_CAPACITY');
        }
        motif = { support: 0, min: part.map((r) => r.at), max: part.map((r) => r.at) };
        motifs.set(key, motif);
      }
      motif.support++;
      part.forEach((row, j) => {
        motif.min[j] = Math.min(motif!.min[j], row.at);
        motif.max[j] = Math.max(motif!.max[j], row.at);
      });
    }
  }
  window.work.distinctMotifs = motifs.size;
  window.sequenceStatus = metrics.sequenceEligibleSessions >= p.minSessions ? 'KNOWN' : 'INSUFFICIENT_SEQUENCE_HISTORY';
  if (window.sequenceStatus !== 'KNOWN') window.issues.push('FEWER_THAN_4_SESSIONS_HAVE_FIVE_ENTRY_EVENTS');
  for (const motif of motifs.values()) {
    metrics.maxMotifSessionSupport = Math.max(metrics.maxMotifSessionSupport, motif.support);
    if (motif.support < p.minSessions) continue;
    metrics.sharedMotifs++;
    if (motif.max.every((value, i) => value - motif.min[i] <= p.synchronyMs)) metrics.synchronizedMotifs++;
  }
  const add = (pattern: CampaignPattern, explanation: string) =>
    window.observations.push({
      key: `${p.version}:${window.endMs}:${window.windowMs}:${pattern}`,
      pattern,
      entryEvents,
      entrySessions: sessions.size,
      explanation,
      limitations,
    });
  if (metrics.sharedMotifs)
    add(
      'SHARED_ENTRY_SEQUENCES',
      `${metrics.sharedMotifs} ordered five-distinct-entry motifs each appear in at least 4 sessions; maximum support ${metrics.maxMotifSessionSupport}; ${entryEvents} entry events across ${sessions.size} sessions. Timing alignment is not required.`,
    );
  if (metrics.synchronizedMotifs >= p.minSynchronizedMotifs)
    add(
      'SYNCHRONIZED_TRAVERSAL',
      `${metrics.synchronizedMotifs} shared motifs have <=10000ms spread at every step of their earliest per-session occurrence (minimum 3 motifs, 4 sessions); ${metrics.sequenceEligibleSessions} sequence-eligible sessions. Overlapping motifs are not independent.`,
    );
  if (
    catalog &&
    metrics.coveredEntries! >= p.coverageMinEntries &&
    metrics.coverageFraction! >= p.coverageFraction &&
    metrics.catalogContributingSessions! >= p.minSessions &&
    metrics.maxSingleSessionCoverage! <= p.maxSingleSessionCoverage
  )
    add(
      'DISTRIBUTED_CATALOG_COVERAGE',
      `${metrics.coveredEntries}/${catalog.size} fixed eligible entries covered across ${metrics.catalogContributingSessions} contributing sessions; largest individual coverage ${metrics.maxSingleSessionCoverage}; criteria >=80%, >=20 entries, >=4 contributors and <=35% individually. No reference population establishes that this breadth is statistically unusual.`,
    );
  return window;
}
